# Reads every admin stylesheet, finds each rule that sets a pixel font-size, and
# writes a matching :root[lang="ur"] rule at a larger size.
#
# Why generated rather than hand-written: the admin CSS sets font-size in ~700
# places. Listing them by hand would miss some and rot the moment a stylesheet
# changes. Re-run this script after changing a stylesheet to refresh the block.
#
# Icons are skipped on purpose. A Font Awesome glyph is sized with font-size too,
# and growing those WOULD move the layout - which is the thing we are avoiding.
import re, io, os, sys

CSS_FILES = ['settings.css', 'main.css', 'index.css', 'manage-students.css',
             'manage-staff.css', 'attendance.css', 'manage-finance.css',
             'reports.css', 'announcements.css', 'examination.css', 'mobile-ui.css']

# Urdu Naskh reads smaller than Inter at the same pixel size, and small text
# suffers most, so the boost tapers as the text gets bigger. Headings are
# already large and only need a nudge.
def scale(px):
    if px <= 11:   f = 1.22
    elif px <= 13.5: f = 1.18
    elif px <= 16: f = 1.12
    elif px <= 22: f = 1.07
    else:          f = 1.04
    return round(px * f, 1)

# A selector that paints an icon glyph, not words.
ICON = re.compile(r'(^|[\s>+~])(i|svg)(\.|:|$|\s)|\.fa[srb]?\b|fa-|::?(before|after)|'
                  r'icon|chevron|arrow|caret|spinner|dot\b|ring-|badge-dot', re.I)
# Things whose size is load-bearing rather than editorial.
# Printed documents - ID cards, certificates, vouchers - are laid out to fixed
# millimetre sizes for paper. Growing their text overflows the card or pushes a
# certificate onto a second page, so they keep the sizes they were designed at.
SKIP = re.compile(r'@font-face|\.toggle-slider|\.ring-|progress|'
                  r'\bidc-|\bsidc-|\bslc-|\bcert-|\bchar-|voucher|print|'
                  r'\bbarcode|\bstamp', re.I)

def rules(css):
    # crude but sufficient: selector { ...declarations... }
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', css):
        yield m.group(1).strip(), m.group(2)

def main():
    seen = {}
    media_depth_note = 0
    for f in CSS_FILES:
        if not os.path.exists(f): continue
        css = io.open(f, encoding='utf-8').read()
        for sel, body in rules(css):
            if sel.startswith('@') or SKIP.search(sel): continue
            m = re.search(r'font-size\s*:\s*([0-9.]+)px', body)
            if not m: continue
            px = float(m.group(1))
            parts = []
            for one in sel.split(','):
                one = one.strip()
                if not one or one.startswith('@') or one.startswith('%'): continue
                if ICON.search(one): continue
                if ':root' in one or one in ('html', '*'): continue
                parts.append(one)
            if not parts: continue
            new = scale(px)
            if new == px: continue
            key = (tuple(parts), px)
            seen[key] = new

    out = []
    out.append('/* ─── generated by tools/gen_urdu_sizes.py - do not edit by hand ───')
    out.append('   One rule per place the admin stylesheets set a pixel font-size.')
    out.append('   Urdu Naskh reads smaller than Inter at the same size, so each is')
    out.append('   scaled up: small text most, headings least. Icon glyphs are left')
    out.append('   alone, because growing those would move the layout. */')
    # group by new size so the file stays readable
    by_size = {}
    for (parts, px), new in seen.items():
        by_size.setdefault((px, new), []).append(parts)
    for (px, new) in sorted(by_size):
        sels = []
        for parts in by_size[(px, new)]:
            for p in parts:
                s = ':root[lang="ur"] ' + p
                if s not in sels: sels.append(s)
        if not sels: continue
        out.append('')
        out.append('/* %gpx -> %gpx */' % (px, new))
        # wrap the selector list
        line, lines = '', []
        for i, s in enumerate(sels):
            piece = s + (',' if i < len(sels) - 1 else '')
            if len(line) + len(piece) > 100:
                lines.append(line); line = piece
            else:
                line = (line + ' ' + piece).strip()
        if line: lines.append(line)
        out.extend(lines)
        out.append('{ font-size: %gpx; }' % new)
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    sys.stdout.write(main())
